let current = 'en';

export function detectLang(pref = 'auto') {
  if (pref === 'ko' || pref === 'en') return pref;
  const nav = (navigator.language || 'en').toLowerCase();
  return nav.startsWith('ko') ? 'ko' : 'en';
}

export function setLang(lang) {
  current = dict[lang] ? lang : 'en';
  document.documentElement.lang = current;
  return current;
}

export function getLang() {
  return current;
}

export function t(key, vars) {
  let s = dict[current][key] ?? dict.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Apply translations to every element with data-i18n / data-i18n-placeholder / data-i18n-title. */
export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const v = t(el.dataset.i18nTitle);
    el.title = v;
    el.setAttribute('aria-label', v);
  });
}
